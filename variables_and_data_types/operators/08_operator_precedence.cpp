#include <iostream>
using namespace std;

int main() {
    int result1 = 10 + 5 * 2;
    int result2 = (10 + 5) * 2;
    int result3 = 20 / 4 + 3 * 2;

    cout << "10 + 5 * 2 = " << result1 << endl;
    cout << "(10 + 5) * 2 = " << result2 << endl;
    cout << "20 / 4 + 3 * 2 = " << result3 << endl;

    return 0;
}
